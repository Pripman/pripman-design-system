#!/usr/bin/env node
/**
 * Bundles src/css into dist/:
 *   dist/pds.css         tokens + base + all components (the `/css` export)
 *   dist/components.css  base + components only, for apps that load tokens separately
 * Everything except tokens is wrapped in cascade layers (pds.base, pds.components)
 * so any unlayered app CSS wins without specificity fights.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src', 'css');
const dist = join(root, 'dist');

const tokensCss = join(dist, 'tokens.css');
if (!existsSync(tokensCss)) {
  console.error('dist/tokens.css missing; run build:tokens first');
  process.exit(1);
}

const read = (f) => readFileSync(f, 'utf8').trim();
const components = readdirSync(join(src, 'components'))
  .filter((f) => f.endsWith('.css'))
  .sort()
  .map((f) => `/* ${f} */\n${read(join(src, 'components', f))}`)
  .join('\n\n');

const indent = (s) => s.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
const layered =
  '@layer pds.base, pds.components;\n\n' +
  `@layer pds.base {\n${indent(read(join(src, 'base.css')))}\n}\n\n` +
  `@layer pds.components {\n${indent(components)}\n}\n`;

const header = '/* @pripman/design-system. Generated by scripts/build-css.mjs. Do not edit. */\n';
writeFileSync(join(dist, 'components.css'), header + layered);
writeFileSync(join(dist, 'pds.css'), header + read(tokensCss).replace(/^\/\*.*\*\/\n/, '') + '\n\n' + layered);
console.log('css: wrote dist/pds.css and dist/components.css');
