#!/usr/bin/env node
/**
 * Builds design tokens from DTCG-style JSON (tokens/**) into:
 *   dist/tokens.css     CSS custom properties (--pds-*), dark (default) + light themes
 *   dist/tailwind.css   Tailwind v4 `@theme inline` mapping onto the CSS variables
 *   dist/tokens.js/.cjs Resolved values for JS (e.g. canvas drawing), plus cssVar()
 *   dist/tokens.d.ts    Types for the above
 *   dist/tokens.json    Flat list with metadata (used by Storybook docs)
 *
 * Primitive tokens live in tokens/primitive/*.json. Each file in
 * tokens/semantic/<theme>.json is a theme; the first entry in THEMES is the
 * default (applied on :root). Semantic tokens may only reference primitives.
 */
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokensDir = join(root, 'tokens');
const outDir = join(root, 'dist');

export const PREFIX = 'pds';
export const THEMES = ['dark', 'light'];

const REF = /\{([^}]+)\}/g;

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/** Flatten a DTCG tree into [{ path, value, type, description }]. */
export function flatten(node, path = [], inheritedType) {
  const type = node.$type ?? inheritedType;
  if (Object.prototype.hasOwnProperty.call(node, '$value')) {
    return [{ path, value: String(node.$value), type, description: node.$description }];
  }
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => flatten(child, [...path, key], type));
}

export const cssName = (path) => `--${PREFIX}-${path.join('-')}`;

/** Resolve {refs} to literal values. Throws on unknown or circular refs. */
export function resolveValue(value, lookup, seen = []) {
  return value.replace(REF, (_, ref) => {
    if (seen.includes(ref)) throw new Error(`Circular token reference: ${[...seen, ref].join(' -> ')}`);
    const target = lookup.get(ref);
    if (!target) throw new Error(`Unknown token reference {${ref}}`);
    return resolveValue(target.value, lookup, [...seen, ref]);
  });
}

/** Replace {refs} with var(--pds-...) so overriding a primitive cascades. */
function toCssValue(value, lookup) {
  return value.replace(REF, (_, ref) => {
    if (!lookup.get(ref)) throw new Error(`Unknown token reference {${ref}}`);
    return `var(${cssName(ref.split('.'))})`;
  });
}

function nest(entries, pick) {
  const out = {};
  for (const entry of entries) {
    let cur = out;
    entry.path.slice(0, -1).forEach((key) => (cur = cur[key] ??= {}));
    cur[entry.path.at(-1)] = pick(entry);
  }
  return out;
}

function typeOf(obj, indent = '  ') {
  if (typeof obj === 'string') return 'string';
  const inner = Object.entries(obj)
    .map(([k, v]) => `${indent}readonly ${JSON.stringify(k)}: ${typeOf(v, indent + '  ')};`)
    .join('\n');
  return `{\n${inner}\n${indent.slice(2)}}`;
}

export function loadTokens(dir = tokensDir) {
  const primitiveDir = join(dir, 'primitive');
  const primitives = readdirSync(primitiveDir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .flatMap((f) => flatten(readJson(join(primitiveDir, f))));

  const lookup = new Map();
  for (const t of primitives) {
    const key = t.path.join('.');
    if (lookup.has(key)) throw new Error(`Duplicate primitive token ${key}`);
    lookup.set(key, t);
  }
  for (const t of primitives) t.resolved = resolveValue(t.value, lookup);

  const themes = {};
  for (const theme of THEMES) {
    const entries = flatten(readJson(join(dir, 'semantic', `${theme}.json`)));
    for (const t of entries) {
      const key = t.path.join('.');
      if (lookup.has(key)) throw new Error(`Semantic token ${key} (${theme}) shadows a primitive`);
      t.resolved = resolveValue(t.value, lookup);
    }
    themes[theme] = entries;
  }

  // Every theme must define exactly the same semantic tokens.
  const names = (entries) => entries.map((t) => t.path.join('.')).sort().join('\n');
  for (const theme of THEMES.slice(1)) {
    if (names(themes[theme]) !== names(themes[THEMES[0]])) {
      const a = new Set(themes[THEMES[0]].map((t) => t.path.join('.')));
      const b = new Set(themes[theme].map((t) => t.path.join('.')));
      const diff = [...a].filter((x) => !b.has(x)).concat([...b].filter((x) => !a.has(x)));
      throw new Error(`Theme "${theme}" does not match "${THEMES[0]}": ${diff.join(', ')}`);
    }
  }
  return { primitives, themes, lookup };
}

const header = '/* Generated by scripts/build-tokens.mjs. Do not edit. */\n';

export function renderCss({ primitives, themes, lookup }) {
  const decl = (entries) =>
    entries.map((t) => `  ${cssName(t.path)}: ${toCssValue(t.value, lookup)};`).join('\n');
  const [defaultTheme, ...rest] = THEMES;
  let css = `${header}:root {\n${decl(primitives)}\n}\n\n`;
  css += `:root,\n[data-theme="${defaultTheme}"] {\n  color-scheme: ${defaultTheme};\n${decl(themes[defaultTheme])}\n}\n`;
  for (const theme of rest) {
    css += `\n[data-theme="${theme}"] {\n  color-scheme: ${theme};\n${decl(themes[theme])}\n}\n`;
  }
  return css;
}

export function renderTailwind({ primitives, themes }) {
  const lines = [];
  // Semantic colours, unprefixed: bg-surface, text-fg, border-border, bg-primary ...
  for (const t of themes[THEMES[0]]) {
    if (t.path[0] === 'color') lines.push(`  --color-${t.path.slice(1).join('-')}: var(${cssName(t.path)});`);
  }
  for (const t of primitives) {
    const [group, ...rest] = t.path;
    const v = `var(${cssName(t.path)})`;
    // Palette prefixed with pds- so it never collides with Tailwind's defaults: bg-pds-oak-500
    if (group === 'color') lines.push(`  --color-pds-${rest.join('-')}: ${v};`);
    else if (group === 'radius') lines.push(`  --radius-${rest.join('-')}: ${v};`);
    else if (group === 'shadow') lines.push(`  --shadow-${rest.join('-')}: ${v};`);
    else if (group === 'font' && rest[0] === 'family') lines.push(`  --font-${rest[1]}: ${v};`);
  }
  return `${header}@theme inline {\n${lines.join('\n')}\n}\n`;
}

export function renderJs({ primitives, themes }) {
  const tokens = nest(primitives, (t) => t.resolved);
  const themeObjs = Object.fromEntries(THEMES.map((th) => [th, nest(themes[th], (t) => t.resolved)]));
  const body = [
    `export const tokens = ${JSON.stringify(tokens, null, 2)};`,
    `export const themes = ${JSON.stringify(themeObjs, null, 2)};`,
    `export const defaultTheme = ${JSON.stringify(THEMES[0])};`,
    `export function cssVar(path) {\n  return 'var(--${PREFIX}-' + path.split('.').join('-') + ')';\n}`,
  ].join('\n\n');
  const esm = `${header}${body}\n`;
  const cjs = `${header}'use strict';\n${body.replace(/export (const|function) (\w+)/g, '$1 $2')}\n\nmodule.exports = { tokens, themes, defaultTheme, cssVar };\n`;

  const paths = [...primitives, ...themes[THEMES[0]]].map((t) => JSON.stringify(t.path.join('.')));
  const dts = `${header}export type TokenPath =\n  | ${paths.join('\n  | ')};\n\n` +
    `export type ThemeName = ${THEMES.map((t) => JSON.stringify(t)).join(' | ')};\n\n` +
    `export declare const tokens: ${typeOf(tokens)};\n\n` +
    `export declare const themes: Record<ThemeName, ${typeOf(themeObjs[THEMES[0]])}>;\n\n` +
    `export declare const defaultTheme: ThemeName;\n\n` +
    `/** \`cssVar('color.oak.500')\` -> \`'var(--${PREFIX}-color-oak-500)'\` */\n` +
    `export declare function cssVar(path: TokenPath): string;\n`;
  return { esm, cjs, dts };
}

export function renderJson({ primitives, themes }) {
  const row = (tier) => (t) => ({
    name: t.path.join('.'),
    cssVar: cssName(t.path),
    tier,
    type: t.type,
    value: t.value,
    resolved: t.resolved,
    ...(t.description ? { description: t.description } : {}),
  });
  return JSON.stringify(
    {
      prefix: PREFIX,
      themes: THEMES,
      primitive: primitives.map(row('primitive')),
      semantic: Object.fromEntries(THEMES.map((th) => [th, themes[th].map(row('semantic'))])),
    },
    null,
    2,
  );
}

export function build() {
  const data = loadTokens();
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'tokens.css'), renderCss(data));
  writeFileSync(join(outDir, 'tailwind.css'), renderTailwind(data));
  const js = renderJs(data);
  writeFileSync(join(outDir, 'tokens.js'), js.esm);
  writeFileSync(join(outDir, 'tokens.cjs'), js.cjs);
  writeFileSync(join(outDir, 'tokens.d.ts'), js.dts);
  writeFileSync(join(outDir, 'tokens.json'), renderJson(data));
  const count = data.primitives.length + THEMES.reduce((n, th) => n + data.themes[th].length, 0);
  console.log(`tokens: wrote ${count} tokens (${THEMES.join(', ')}) to dist/`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build();
